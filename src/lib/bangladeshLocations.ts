export const FALLBACK_UPAZILAS: Upazila[] = [];
let upaCounter = 1;
FALLBACK_DISTRICTS.forEach((dis) => {
  const customList = RAW_UPAZILAS_BY_DISTRICT_NAME[dis.name_bn] || [
    `${dis.name_bn} সদর`,
    `${dis.name_bn} উত্তর`,
    `${dis.name_bn} দক্ষিণ`,
  ];
  customList.forEach((uName) => {
    FALLBACK_UPAZILAS.push({
      id: `fallback-upa-${upaCounter++}`,
      district_id: dis.id,
      name_bn: uName,
      is_active: true,
    });
  });
});

export function getFallbackUpazilasForDistrictName(districtNameBn: string, targetDistrictId: string): Upazila[] {
  const list = RAW_UPAZILAS_BY_DISTRICT_NAME[districtNameBn] || [`${districtNameBn} সদর`];
  return list.map((name_bn, idx) => ({
    id: `fallback-upa-${targetDistrictId}-${idx + 1}`,
    district_id: targetDistrictId,
    name_bn,
    is_active: true,
  }));
}
